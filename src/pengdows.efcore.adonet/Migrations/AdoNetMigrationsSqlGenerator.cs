using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Migrations;
using Microsoft.EntityFrameworkCore.Migrations.Operations;

namespace pengdows.efcore.adonet.Migrations;

/// <summary>
///     ISO SQL DDL, filling in what EF's base generator leaves to providers (altering and renaming columns, tables, indexes
///     and sequences, schemas, computed and identity columns). A dialect subclasses this for what its database writes
///     differently and registers it in <see cref="IAdoNetDialect.ConfigureServices" />.
/// </summary>
public class AdoNetMigrationsSqlGenerator(MigrationsSqlGeneratorDependencies dependencies, IAdoNetDialect dialect)
    : MigrationsSqlGenerator(dependencies)
{
    protected IAdoNetDialect Dialect { get; } = dialect;

    protected override void Generate(CreateTableOperation operation, IModel? model, MigrationCommandListBuilder builder, bool terminate = true)
    {
        // Sequence-key dialects have no identity columns; the key's sequence is created with the table.
        if (Dialect.Sql.Keys is SequenceKeyRetrieval keys)
        {
            foreach (var column in operation.Columns.Where(IsIdentity))
            {
                builder
                    .Append("CREATE SEQUENCE ")
                    .Append(Dependencies.SqlGenerationHelper.DelimitIdentifier(keys.GetSequenceName(operation.Name, column.Name), operation.Schema))
                    .AppendLine(Dependencies.SqlGenerationHelper.StatementTerminator);
                EndStatement(builder);
            }
        }

        base.Generate(operation, model, builder, terminate);
    }

    protected override void Generate(DropTableOperation operation, IModel? model, MigrationCommandListBuilder builder, bool terminate = true)
    {
        base.Generate(operation, model, builder, terminate);

        foreach (var sequence in IdentitySequences(operation.Name, operation.Schema, operation))
        {
            builder.Append("DROP SEQUENCE ").Append(sequence).AppendLine(Dependencies.SqlGenerationHelper.StatementTerminator);
            EndStatement(builder);
        }
    }

    private IEnumerable<string> IdentitySequences(string table, string? schema, MigrationOperation operation)
        => Dialect.Sql.Keys is SequenceKeyRetrieval keys && operation[AdoNetAnnotationNames.IdentityColumns] is string[] columns
            ? columns.Select(c => Dependencies.SqlGenerationHelper.DelimitIdentifier(keys.GetSequenceName(table, c), schema))
            : [];

    /// <summary>Name, type, default, identity, NOT NULL, collation; a nullable column has no NULL keyword, which isn't ISO SQL.</summary>
    protected override void ColumnDefinition(
        string? schema,
        string table,
        string name,
        ColumnOperation operation,
        IModel? model,
        MigrationCommandListBuilder builder)
    {
        if (operation.ComputedColumnSql != null)
        {
            ComputedColumnDefinition(schema, table, name, operation, model, builder);
            return;
        }

        var columnType = operation.ColumnType ?? GetColumnType(schema, table, name, operation, model)!;
        builder.Append(Dependencies.SqlGenerationHelper.DelimitIdentifier(name)).Append(" ").Append(columnType);

        DefaultValue(operation.DefaultValue, operation.DefaultValueSql, columnType, builder);

        if (IsIdentity(operation) && Dialect.Sql.Keys is not SequenceKeyRetrieval)
        {
            IdentityDefinition(schema, table, name, operation, builder);
        }

        if (!operation.IsNullable)
        {
            builder.Append(" NOT NULL");
        }

        if (operation.Collation != null)
        {
            builder.Append(" COLLATE ").Append(Dependencies.SqlGenerationHelper.DelimitIdentifier(operation.Collation));
        }
    }

    /// <summary>Written after a database-generated key column's type: <c>GENERATED BY DEFAULT AS IDENTITY</c> (SQL:2003).</summary>
    protected virtual void IdentityDefinition(string? schema, string table, string name, ColumnOperation operation, MigrationCommandListBuilder builder)
        => builder.Append(" GENERATED BY DEFAULT AS IDENTITY");

    protected override void ComputedColumnDefinition(
        string? schema,
        string table,
        string name,
        ColumnOperation operation,
        IModel? model,
        MigrationCommandListBuilder builder)
    {
        builder
            .Append(Dependencies.SqlGenerationHelper.DelimitIdentifier(name))
            .Append(" ")
            .Append(operation.ColumnType ?? GetColumnType(schema, table, name, operation, model)!)
            .Append(" GENERATED ALWAYS AS (")
            .Append(operation.ComputedColumnSql!)
            .Append(")");

        if (operation.IsStored == true)
        {
            builder.Append(" STORED");
        }
    }

    /// <summary>
    ///     One <c>ALTER COLUMN</c> statement per changed aspect: type, nullability, default. ISO SQL has no statement for a
    ///     change of collation, computed expression or identity, so those are refused rather than skipped.
    /// </summary>
    protected override void Generate(AlterColumnOperation operation, IModel? model, MigrationCommandListBuilder builder)
    {
        var oldColumn = operation.OldColumn;
        RefuseUnalterable(operation, oldColumn);

        // The old type from the operation's own facets: the model, when there is one, only knows the new column.
        var type = operation.ColumnType ?? GetColumnType(operation.Schema, operation.Table, operation.Name, operation, model);
        var oldType = oldColumn.ColumnType ?? GetColumnType(operation.Schema, operation.Table, operation.Name, oldColumn, model: null);
        if (!string.Equals(type, oldType, StringComparison.OrdinalIgnoreCase))
        {
            AlterColumn(operation, builder).Append(" SET DATA TYPE ").Append(type!);
            builder.AppendLine(Dependencies.SqlGenerationHelper.StatementTerminator);
            EndStatement(builder);
        }

        if (operation.IsNullable != oldColumn.IsNullable)
        {
            AlterColumn(operation, builder).Append(operation.IsNullable ? " DROP NOT NULL" : " SET NOT NULL");
            builder.AppendLine(Dependencies.SqlGenerationHelper.StatementTerminator);
            EndStatement(builder);
        }

        if (!Equals(operation.DefaultValue, oldColumn.DefaultValue) || operation.DefaultValueSql != oldColumn.DefaultValueSql)
        {
            AlterColumn(operation, builder);
            if (operation.DefaultValue == null && operation.DefaultValueSql == null)
            {
                builder.Append(" DROP DEFAULT");
            }
            else
            {
                builder.Append(" SET");
                DefaultValue(operation.DefaultValue, operation.DefaultValueSql, type, builder);
            }

            builder.AppendLine(Dependencies.SqlGenerationHelper.StatementTerminator);
            EndStatement(builder);
        }
    }

    private void RefuseUnalterable(AlterColumnOperation operation, ColumnOperation oldColumn)
    {
        var change = operation.Collation != oldColumn.Collation ? "collation"
            : (operation.ComputedColumnSql != oldColumn.ComputedColumnSql) || (operation.IsStored != oldColumn.IsStored) ? "computed expression"
            : IsIdentity(operation) != IsIdentity(oldColumn) ? "identity"
            : null;
        if (change != null)
        {
            throw new NotSupportedException(
                $"Dialect '{Dialect.Name}': '{operation.Table}.{operation.Name}' changes its {change}, which ISO SQL can't alter in "
                + "place. Rebuild the column in the migration (add, copy, drop, rename).");
        }
    }

    private MigrationCommandListBuilder AlterColumn(AlterColumnOperation operation, MigrationCommandListBuilder builder)
        => builder
            .Append("ALTER TABLE ")
            .Append(Dependencies.SqlGenerationHelper.DelimitIdentifier(operation.Table, operation.Schema))
            .Append(" ALTER COLUMN ")
            .Append(Dependencies.SqlGenerationHelper.DelimitIdentifier(operation.Name));

    protected override void Generate(RenameColumnOperation operation, IModel? model, MigrationCommandListBuilder builder)
    {
        builder
            .Append("ALTER TABLE ")
            .Append(Dependencies.SqlGenerationHelper.DelimitIdentifier(operation.Table, operation.Schema))
            .Append(" RENAME COLUMN ")
            .Append(Dependencies.SqlGenerationHelper.DelimitIdentifier(operation.Name))
            .Append(" TO ")
            .Append(Dependencies.SqlGenerationHelper.DelimitIdentifier(operation.NewName))
            .AppendLine(Dependencies.SqlGenerationHelper.StatementTerminator);
        EndStatement(builder);
    }

    protected override void Generate(RenameTableOperation operation, IModel? model, MigrationCommandListBuilder builder)
    {
        if (operation.NewSchema != operation.Schema && Dialect.Sql.SupportsSchemas)
        {
            throw new NotSupportedException($"Dialect '{Dialect.Name}': moving a table to another schema has no ISO SQL form.");
        }

        builder
            .Append("ALTER TABLE ")
            .Append(Dependencies.SqlGenerationHelper.DelimitIdentifier(operation.Name, operation.Schema))
            .Append(" RENAME TO ")
            .Append(Dependencies.SqlGenerationHelper.DelimitIdentifier(operation.NewName ?? operation.Name))
            .AppendLine(Dependencies.SqlGenerationHelper.StatementTerminator);
        EndStatement(builder);
        if (Dialect.Sql.Keys is SequenceKeyRetrieval keys && operation[AdoNetAnnotationNames.IdentityColumns] is string[] columns)
        {
            foreach (var column in columns)
            {
                builder
                    .Append("ALTER SEQUENCE ")
                    .Append(Dependencies.SqlGenerationHelper.DelimitIdentifier(keys.GetSequenceName(operation.Name, column), operation.Schema))
                    .Append(" RENAME TO ")
                    .Append(Dependencies.SqlGenerationHelper.DelimitIdentifier(keys.GetSequenceName(operation.NewName ?? operation.Name, column)))
                    .AppendLine(Dependencies.SqlGenerationHelper.StatementTerminator);
                EndStatement(builder);
            }
        }
    }

    protected override void Generate(RenameIndexOperation operation, IModel? model, MigrationCommandListBuilder builder)
    {
        builder
            .Append("ALTER INDEX ")
            .Append(Dependencies.SqlGenerationHelper.DelimitIdentifier(operation.Name, operation.Schema))
            .Append(" RENAME TO ")
            .Append(Dependencies.SqlGenerationHelper.DelimitIdentifier(operation.NewName))
            .AppendLine(Dependencies.SqlGenerationHelper.StatementTerminator);
        EndStatement(builder);
    }

    protected override void Generate(RenameSequenceOperation operation, IModel? model, MigrationCommandListBuilder builder)
    {
        builder
            .Append("ALTER SEQUENCE ")
            .Append(Dependencies.SqlGenerationHelper.DelimitIdentifier(operation.Name, operation.Schema))
            .Append(" RENAME TO ")
            .Append(Dependencies.SqlGenerationHelper.DelimitIdentifier(operation.NewName ?? operation.Name))
            .AppendLine(Dependencies.SqlGenerationHelper.StatementTerminator);
        EndStatement(builder);
    }

    protected override void Generate(DropIndexOperation operation, IModel? model, MigrationCommandListBuilder builder, bool terminate = true)
    {
        builder
            .Append("DROP INDEX ")
            .Append(Dependencies.SqlGenerationHelper.DelimitIdentifier(operation.Name, operation.Schema));

        if (terminate)
        {
            builder.AppendLine(Dependencies.SqlGenerationHelper.StatementTerminator);
            EndStatement(builder);
        }
    }

    /// <summary><c>CREATE SCHEMA IF NOT EXISTS</c>; nothing for dialects without schemas.</summary>
    protected override void Generate(EnsureSchemaOperation operation, IModel? model, MigrationCommandListBuilder builder)
    {
        if (!Dialect.Sql.SupportsSchemas)
        {
            return;
        }

        builder
            .Append("CREATE SCHEMA IF NOT EXISTS ")
            .Append(Dependencies.SqlGenerationHelper.DelimitIdentifier(operation.Name))
            .AppendLine(Dependencies.SqlGenerationHelper.StatementTerminator);
        EndStatement(builder);
    }

    protected static bool IsIdentity(ColumnOperation column)
        => column[AdoNetAnnotationNames.Identity] is true;
}
