using Microsoft.EntityFrameworkCore;

namespace pengdows.efcore.adonet.postgresql.Tests;

/// <summary>Binary COPY writes each value as its column's type, not the type .NET would guess for it.</summary>
public class PostgreSqlBulkTests(PostgreSqlFixture fixture) : IClassFixture<PostgreSqlFixture>
{
    private static CancellationToken Ct
        => TestContext.Current.CancellationToken;

    [Fact]
    public async Task Copy_writes_values_as_the_column_type()
    {
        await fixture.ExecuteAsync("""
            CREATE TABLE IF NOT EXISTS "Readings" (
                "Id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                "Day" DATE NOT NULL,
                "Total" BIGINT NOT NULL)
            """);
        await fixture.ExecuteAsync("""DELETE FROM "Readings" """);
        var day = new DateTime(2026, 5, 6);

        await using (var context = fixture.CreateContext<ReadingContext>(o => new ReadingContext(o)))
        {
            await context.BulkInsertAsync([new Reading { Day = day, Total = 7 }], Ct);
        }

        await using (var context = fixture.CreateContext<ReadingContext>(o => new ReadingContext(o)))
        {
            var reading = await context.Readings.SingleAsync(Ct);
            Assert.Equal((day, 7L), (reading.Day, reading.Total));
        }
    }

    public class Reading
    {
        public int Id { get; set; }
        public DateTime Day { get; set; }
        public long Total { get; set; }
    }

    public class ReadingContext(DbContextOptions<ReadingContext> options) : DbContext(options)
    {
        public DbSet<Reading> Readings => Set<Reading>();

        protected override void OnModelCreating(ModelBuilder modelBuilder)
            => modelBuilder.Entity<Reading>().Property(r => r.Day).HasColumnType("date");
    }
}
