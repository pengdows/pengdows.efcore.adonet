using System.Data.Common;
using DotNet.Testcontainers.Containers;
using Microsoft.EntityFrameworkCore;
using Npgsql;
using Testcontainers.PostgreSql;
using pengdows.efcore.adonet.Testing;

namespace pengdows.efcore.adonet.postgresql.Tests;

public sealed class PostgreSqlFixture : ContainerFixture
{
    public override DbProviderFactory Factory => NpgsqlFactory.Instance;
    public override IAdoNetDialect ExpectedDialect => PostgreSqlDialect.Instance;

    protected override void UseProvider(DbContextOptionsBuilder builder)
        => builder.UseAdoNetPostgreSql(ConnectionString);

    protected override IDatabaseContainer CreateContainer()
        => new PostgreSqlBuilder("postgres:17-alpine").Build();

    protected override IEnumerable<string> Ddl =>
    [
        """
        CREATE TABLE "Blogs" (
            "Id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "Name" VARCHAR NOT NULL,
            "IsActive" BOOLEAN NOT NULL,
            "Rating" DECIMAL(18,2) NOT NULL,
            "CreatedAt" TIMESTAMP NOT NULL,
            "ExternalId" UUID NOT NULL)
        """,
        """
        CREATE TABLE "Posts" (
            "Id" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            "BlogId" INTEGER NOT NULL,
            "Title" VARCHAR NOT NULL)
        """
    ];
}

public class PostgreSqlConformanceTests(PostgreSqlFixture fixture) : ProviderConformanceTests<PostgreSqlFixture>(fixture);

public class PostgreSqlMigrationsConformanceTests(PostgreSqlFixture fixture) : MigrationsConformanceTests<PostgreSqlFixture>(fixture);

public class PostgreSqlBulkConformanceTests(PostgreSqlFixture fixture) : BulkConformanceTests<PostgreSqlFixture>(fixture);
