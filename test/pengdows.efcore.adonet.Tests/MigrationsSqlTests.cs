using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Infrastructure;
using Microsoft.EntityFrameworkCore.Metadata;
using Microsoft.EntityFrameworkCore.Migrations;
using Microsoft.EntityFrameworkCore.Migrations.Operations;
using Microsoft.EntityFrameworkCore.Storage;

namespace pengdows.efcore.adonet.Tests;

/// <summary>The ISO DDL the core writes for migration operations EF's base generator leaves to providers.</summary>
public class MigrationsSqlTests
{
    private static string Sql(IAdoNetDialect dialect, params MigrationOperation[] operations)
    {
        using var context = new FakeDatabase().Context(dialect);
        return string.Join("", context.GetService<IMigrationsSqlGenerator>().Generate(operations).Select(c => c.CommandText))
            .ReplaceLineEndings("\n");
    }

    [Fact]
    public void Sized_types_come_from_the_dialect()
    {
        using var context = new FakeDatabase().Context(AdoNetDialect.Ansi);
        var source = context.GetService<IRelationalTypeMappingSource>();

        Assert.Equal("VARCHAR(40)", source.FindMapping(typeof(string), null, false, null, 40)!.StoreType);
        Assert.Equal("VARCHAR(20)", source.FindMapping(typeof(string), null, false, null, 20)!.StoreType);
        Assert.Equal("DECIMAL(10,2)", source.FindMapping(typeof(decimal), null, false, null, null, false, false, 10, 2)!.StoreType);
        Assert.Equal("VARCHAR", source.FindMapping(typeof(string))!.StoreType);
    }

    [Fact]
    public void Alter_column_writes_one_statement_per_changed_aspect()
    {
        var sql = Sql(
            AdoNetDialect.Ansi,
            new AlterColumnOperation
            {
                Table = "Shelves", Name = "Code", ClrType = typeof(string), MaxLength = 40, IsNullable = false, DefaultValue = "none",
                OldColumn = new AddColumnOperation { Table = "Shelves", Name = "Code", ClrType = typeof(string), MaxLength = 20, IsNullable = true }
            });

        Assert.Equal(
            "ALTER TABLE \"Shelves\" ALTER COLUMN \"Code\" SET DATA TYPE VARCHAR(40);\n"
            + "ALTER TABLE \"Shelves\" ALTER COLUMN \"Code\" SET NOT NULL;\n"
            + "ALTER TABLE \"Shelves\" ALTER COLUMN \"Code\" SET DEFAULT 'none';\n",
            sql);
    }

    private static AddColumnOperation Column(string name, Type type, bool nullable = false, string table = "T")
        => new() { Table = table, Name = name, ClrType = type, IsNullable = nullable };

    private static CreateTableOperation Table(string name, params AddColumnOperation[] columns)
    {
        var table = new CreateTableOperation { Name = name, PrimaryKey = new AddPrimaryKeyOperation { Name = "PK_" + name, Table = name, Columns = ["Id"] } };
        table.Columns.AddRange(columns);
        return table;
    }

    private static AddColumnOperation IdentityColumn(string table = "T")
    {
        var id = Column("Id", typeof(int), table: table);
        id.AddAnnotation(AdoNetAnnotationNames.Identity, true);
        return id;
    }

    [Fact]
    public void Columns_are_written_in_iso_order_with_identity()
    {
        var name = Column("Name", typeof(string), nullable: true);
        name.Collation = "C";
        var rating = Column("Rating", typeof(int));
        rating.DefaultValue = 3;

        Assert.Equal(
            "CREATE TABLE \"T\" (\n    \"Id\" INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n    \"Name\" VARCHAR COLLATE \"C\",\n"
            + "    \"Rating\" INTEGER DEFAULT 3 NOT NULL,\n    CONSTRAINT \"PK_T\" PRIMARY KEY (\"Id\")\n);\n",
            Sql(AdoNetDialect.Ansi, Table("T", IdentityColumn(), name, rating)));
    }

    [Fact]
    public void Computed_columns_are_generated_always()
    {
        var stored = Column("Total", typeof(int));
        stored.ComputedColumnSql = "\"A\" + \"B\"";
        stored.IsStored = true;
        var virtualColumn = Column("Half", typeof(int));
        virtualColumn.ComputedColumnSql = "\"A\" / 2";

        var sql = Sql(AdoNetDialect.Ansi, Table("T", Column("Id", typeof(int)), stored, virtualColumn));

        Assert.Contains("\"Total\" INTEGER GENERATED ALWAYS AS (\"A\" + \"B\") STORED,", sql);
        Assert.Contains("\"Half\" INTEGER GENERATED ALWAYS AS (\"A\" / 2),", sql);
    }

    [Fact]
    public void Sequence_key_dialects_keep_a_sequence_with_the_table()
    {
        var drop = new DropTableOperation { Name = "T" };
        drop.AddAnnotation(AdoNetAnnotationNames.IdentityColumns, new[] { "Id" });
        var rename = new RenameTableOperation { Name = "T", NewName = "U" };
        rename.AddAnnotation(AdoNetAnnotationNames.IdentityColumns, new[] { "Id" });

        Assert.Equal(
            "CREATE SEQUENCE \"T_Id_seq\";\nCREATE TABLE \"T\" (\n    \"Id\" INTEGER NOT NULL,\n    CONSTRAINT \"PK_T\" PRIMARY KEY (\"Id\")\n);\n",
            Sql(TestDialects.Sequence, Table("T", IdentityColumn())));
        Assert.Equal("DROP TABLE \"T\";\nDROP SEQUENCE \"T_Id_seq\";\n", Sql(TestDialects.Sequence, drop));
        Assert.Equal(
            "ALTER TABLE \"T\" RENAME TO \"U\";\nALTER SEQUENCE \"T_Id_seq\" RENAME TO \"U_Id_seq\";\n",
            Sql(TestDialects.Sequence, rename));

        // Other dialects have identity columns; the annotation changes nothing for them.
        Assert.Equal("DROP TABLE \"T\";\n", Sql(AdoNetDialect.Ansi, drop));
        Assert.Equal("ALTER TABLE \"T\" RENAME TO \"U\";\n", Sql(AdoNetDialect.Ansi, rename));
    }

    [Fact]
    public void Alter_column_writes_only_what_changed()
    {
        AlterColumnOperation Alter(Action<AlterColumnOperation> change)
        {
            var operation = new AlterColumnOperation
            {
                Table = "T", Name = "C", ClrType = typeof(string), MaxLength = 20, IsNullable = false, DefaultValue = "x",
                OldColumn = new AddColumnOperation { Table = "T", Name = "C", ClrType = typeof(string), MaxLength = 20, IsNullable = false, DefaultValue = "x" }
            };
            change(operation);
            return operation;
        }

        Assert.Equal("", Sql(AdoNetDialect.Ansi, Alter(_ => { })));
        Assert.Equal(
            "ALTER TABLE \"T\" ALTER COLUMN \"C\" DROP NOT NULL;\nALTER TABLE \"T\" ALTER COLUMN \"C\" DROP DEFAULT;\n",
            Sql(AdoNetDialect.Ansi, Alter(o => { o.IsNullable = true; o.DefaultValue = null; })));
        Assert.Equal(
            "ALTER TABLE \"T\" ALTER COLUMN \"C\" SET DEFAULT (now());\n",
            Sql(AdoNetDialect.Ansi, Alter(o => { o.DefaultValue = null; o.DefaultValueSql = "now()"; })));
        Assert.Equal(
            "ALTER TABLE \"T\" ALTER COLUMN \"C\" SET DATA TYPE TEXT;\n",
            Sql(AdoNetDialect.Ansi, Alter(o => o.ColumnType = "TEXT")));
    }

    [Fact]
    public void Alter_column_refuses_changes_it_has_no_statement_for()
    {
        AlterColumnOperation Alter(Action<AlterColumnOperation> change)
        {
            var operation = new AlterColumnOperation
            {
                Table = "T", Name = "C", ClrType = typeof(int), IsNullable = false,
                OldColumn = new AddColumnOperation { Table = "T", Name = "C", ClrType = typeof(int), IsNullable = false }
            };
            change(operation);
            return operation;
        }

        Assert.Contains("collation", Assert.Throws<NotSupportedException>(() => Sql(AdoNetDialect.Ansi, Alter(o => o.Collation = "C"))).Message);
        Assert.Contains("computed", Assert.Throws<NotSupportedException>(() => Sql(AdoNetDialect.Ansi, Alter(o => o.ComputedColumnSql = "1"))).Message);
        Assert.Contains("computed", Assert.Throws<NotSupportedException>(() => Sql(AdoNetDialect.Ansi, Alter(o => o.IsStored = true))).Message);
        Assert.Contains("identity", Assert.Throws<NotSupportedException>(
            () => Sql(AdoNetDialect.Ansi, Alter(o => o.AddAnnotation(AdoNetAnnotationNames.Identity, true)))).Message);
    }

    [Fact]
    public void The_differ_records_identity_columns_of_dropped_and_renamed_tables()
    {
        using var context = new FakeDatabase().Context(TestDialects.Sequence);
        var items = context.GetService<IDesignTimeModel>().Model.GetRelationalModel();

        var drop = context.GetService<IMigrationsModelDiffer>().GetDifferences(items, null).OfType<DropTableOperation>().Single(o => o.Name == "Items");
        var rename = context.GetService<IMigrationsAnnotationProvider>().ForRename(items.FindTable("Items", null)!);

        Assert.Equal(["Id"], (string[])drop[AdoNetAnnotationNames.IdentityColumns]!);
        Assert.Equal(["Id"], (string[])rename.Single(a => a.Name == AdoNetAnnotationNames.IdentityColumns).Value!);
    }

    [Fact]
    public void Hostile_identifiers_are_delimited_in_ddl()
    {
        var create = new CreateTableOperation
        {
            Name = "Order\"; DROP TABLE x; --",
            Schema = "select",
            Columns = { new AddColumnOperation { Name = "a\"b", Table = "Order", ClrType = typeof(int) } }
        };

        Assert.StartsWith(
            "CREATE TABLE \"select\".\"Order\"\"; DROP TABLE x; --\" (\n    \"a\"\"b\" INTEGER NOT NULL",
            Sql(AdoNetDialect.Ansi, create));
    }

    [Fact]
    public void Renames_use_iso_alter_statements()
    {
        Assert.Equal(
            "ALTER TABLE \"s\".\"T\" RENAME COLUMN \"A\" TO \"B\";\n",
            Sql(AdoNetDialect.Ansi, new RenameColumnOperation { Schema = "s", Table = "T", Name = "A", NewName = "B" }));
        Assert.Equal(
            "ALTER INDEX \"s\".\"IX_A\" RENAME TO \"IX_B\";\n",
            Sql(AdoNetDialect.Ansi, new RenameIndexOperation { Schema = "s", Table = "T", Name = "IX_A", NewName = "IX_B" }));
        Assert.Equal(
            "ALTER SEQUENCE \"s\".\"Q\" RENAME TO \"R\";\n",
            Sql(AdoNetDialect.Ansi, new RenameSequenceOperation { Schema = "s", Name = "Q", NewName = "R", NewSchema = "s" }));
        Assert.Equal(
            "ALTER TABLE \"s\".\"T\" RENAME TO \"U\";\n",
            Sql(AdoNetDialect.Ansi, new RenameTableOperation { Schema = "s", Name = "T", NewName = "U", NewSchema = "s" }));
        Assert.Equal("DROP INDEX \"s\".\"IX\";\n", Sql(AdoNetDialect.Ansi, new DropIndexOperation { Schema = "s", Table = "T", Name = "IX" }));
    }

    [Fact]
    public void Moving_a_table_between_schemas_is_refused_where_schemas_exist()
    {
        var move = new RenameTableOperation { Schema = "a", Name = "T", NewSchema = "b", NewName = "T" };

        Assert.Throws<NotSupportedException>(() => Sql(AdoNetDialect.Ansi, move));
        Assert.Equal("ALTER TABLE \"T\" RENAME TO \"T\";\n", Sql(TestDialects.ColonParameters, move));
    }

    [Fact]
    public void Schemas_are_ensured_only_where_they_exist()
    {
        Assert.Equal("CREATE SCHEMA IF NOT EXISTS \"s\";\n", Sql(AdoNetDialect.Ansi, new EnsureSchemaOperation { Name = "s" }));
        Assert.Equal("", Sql(TestDialects.ColonParameters, new EnsureSchemaOperation { Name = "s" }));
    }

    [Fact]
    public void Database_generated_integer_keys_are_marked_as_identity()
    {
        using var context = new FakeDatabase().Context(AdoNetDialect.Ansi);
        var model = context.GetService<IDesignTimeModel>().Model;
        bool Identity<TEntity>(string property)
            => model.FindEntityType(typeof(TEntity))!.FindProperty(property)!.FindAnnotation(AdoNetAnnotationNames.Identity)?.Value is true;

        Assert.True(Identity<Item>(nameof(Item.Id)));
        Assert.True(Identity<LongKeyed>(nameof(LongKeyed.Id)));
        Assert.True(Identity<ShortKeyed>(nameof(ShortKeyed.Id)));
        Assert.False(Identity<Part>(nameof(Part.ItemId)));
        Assert.False(Identity<Item>(nameof(Item.Version)));

        var create = context.GetService<IMigrationsModelDiffer>().GetDifferences(null, model.GetRelationalModel())
            .OfType<CreateTableOperation>().Single(t => t.Name == "Items");
        Assert.Equal(true, create.Columns.Single(c => c.Name == "Id")[AdoNetAnnotationNames.Identity]);
        Assert.Null(create.Columns.Single(c => c.Name == "Name")[AdoNetAnnotationNames.Identity]);
    }

    [Fact]
    public void Names_are_shortened_to_the_databases_identifier_length()
    {
        var shortNames = new PartsDialect("Ten-character identifiers", capabilities: new DatabaseCapabilities { MaxIdentifierLength = 10 });
        using var context = new FakeDatabase().Context(shortNames);
        var model = context.GetService<IDesignTimeModel>().Model.GetRelationalModel();

        var names = model.Tables.SelectMany(
            t => t.Columns.Select(c => c.Name)
                .Concat(t.UniqueConstraints.Select(u => u.Name))
                .Concat(t.ForeignKeyConstraints.Select(f => f.Name))
                .Concat(t.Indexes.Select(i => i.Name))
                .Append(t.Name)).ToList();
        Assert.Contains(names, n => n.StartsWith("FK_", StringComparison.Ordinal));
        Assert.All(names, n => Assert.True(n.Length <= 10, n));
    }

    [Fact]
    public void Iso_identifiers_are_up_to_128_characters()
        => Assert.Equal(128, DatabaseCapabilities.Default.MaxIdentifierLength);

    [Fact]
    public void Keys_with_a_configured_default_are_not_identity()
    {
        using var context = new KeyDefaultsContext(
            new Microsoft.EntityFrameworkCore.DbContextOptionsBuilder<KeyDefaultsContext>()
                .UseAdoNet(new FakeDatabase().Connection, false, o => o.UseDialect(AdoNetDialect.Ansi)).AllowManyDialects().Options);
        var model = context.GetService<IDesignTimeModel>().Model;

        Assert.All(
            model.GetEntityTypes(),
            e => Assert.Null(e.FindPrimaryKey()!.Properties[0].FindAnnotation(AdoNetAnnotationNames.Identity)));
    }

    private sealed class KeyDefaultsContext(Microsoft.EntityFrameworkCore.DbContextOptions<KeyDefaultsContext> options)
        : Microsoft.EntityFrameworkCore.DbContext(options)
    {
        protected override void OnModelCreating(Microsoft.EntityFrameworkCore.ModelBuilder modelBuilder)
        {
            modelBuilder.Entity<LongKeyed>().Property(e => e.Id).HasDefaultValue(5L);
            modelBuilder.Entity<ShortKeyed>().Property(e => e.Id).HasDefaultValueSql("1");
            modelBuilder.Entity<Part>(e =>
            {
                e.Property(p => p.Id).ValueGeneratedNever();
                e.Ignore(p => p.Item);
            });
            modelBuilder.Entity<Defaulted>().HasKey(d => new { d.Id, d.Counter });
        }
    }
}
