    // EF's TPC key is generated by a sequence where there is one; MySQL has none, so the child's key is AUTO_INCREMENT, which
    // EF warns can repeat across a hierarchy's tables. Adapted from Pomelo's StoredProcedureUpdateMySqlTest (MIT, Pomelo
    // Foundation):
    // https://github.com/PomeloFoundation/Pomelo.EntityFrameworkCore.MySql/blob/14c2cd558e37c71e7a2fca75e339ef902effdf60/test/EFCore.MySql.FunctionalTests/Update/StoredProcedureUpdateMySqlTest.cs
    public override async Task Tpc(bool async)
    {
        var contextFactory = await InitializeAsync<DbContext>(
            modelBuilder =>
            {
                modelBuilder.Entity<Parent>().UseTpcMappingStrategy();
                modelBuilder.Entity<Child1>()
                    .UseTpcMappingStrategy()
                    .InsertUsingStoredProcedure(
                        nameof(Child1) + "_Insert",
                        spb => spb
                            .HasParameter(w => w.Id, pb => pb.IsOutput())
                            .HasParameter(w => w.Name)
                            .HasParameter(w => w.Child1Property))
                    .Property(e => e.Id).UseIdentityColumn();
            },
            seed: ctx => CreateStoredProcedures(ctx, UpdateProcedureSql.Of<MySqlHost>(nameof(Tpc))),
            onConfiguring: optionsBuilder => optionsBuilder.ConfigureWarnings(w => w.Ignore(RelationalEventId.TpcStoreGeneratedIdentityWarning)));

        await using var context = contextFactory.CreateContext();
        var entity1 = new Child1 { Name = "Child", Child1Property = 8 };
        context.Set<Child1>().Add(entity1);
        if (async)
        {
            await context.SaveChangesAsync();
        }
        else
        {
            context.SaveChanges();
        }

        context.ChangeTracker.Clear();
        var entity2 = context.Set<Child1>().Single(b => b.Id == entity1.Id);
        Assert.Equal("Child", entity2.Name);
        Assert.Equal(8, entity2.Child1Property);
    }
}
