using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Diagnostics;
using pengdows.efcore.adonet;

namespace pengdows.efcore.adonet.Specification.Tests.PostgreSql;

// A PostgreSQL procedure returns its outputs as the OUT parameters of CALL, a single row, and cannot return a result set or a
// return value. The suite's cases for those shapes ask for behaviour the procedure contract does not have, so they are skipped
// with the reason, as MySQL's are.
public partial class StoredProcedureUpdatePostgreSqlTest
{
    private const string PostgreSqlNoResultColumns = "[SKIP:PostgreSQL] A procedure's outputs come back from CALL as OUT parameters, "
        + "so it cannot also return result columns";

    private const string PostgreSqlNoReturnValue = "[SKIP:PostgreSQL] PostgreSQL procedures have no return value";

    [ConditionalTheory(Skip = PostgreSqlNoResultColumns)]
    [MemberData(nameof(IsAsyncData))]
    public override Task Insert_with_result_column(bool async)
        => base.Insert_with_result_column(async);

    [ConditionalTheory(Skip = PostgreSqlNoResultColumns)]
    [MemberData(nameof(IsAsyncData))]
    public override Task Insert_with_two_result_columns(bool async)
        => base.Insert_with_two_result_columns(async);

    [ConditionalTheory(Skip = PostgreSqlNoResultColumns)]
    [MemberData(nameof(IsAsyncData))]
    public override Task Insert_with_output_parameter_and_result_column(bool async)
        => base.Insert_with_output_parameter_and_result_column(async);

    [ConditionalTheory(Skip = PostgreSqlNoResultColumns)]
    [MemberData(nameof(IsAsyncData))]
    public override Task Rows_affected_result_column(bool async)
        => base.Rows_affected_result_column(async);

    [ConditionalTheory(Skip = PostgreSqlNoResultColumns)]
    [MemberData(nameof(IsAsyncData))]
    public override Task Rows_affected_result_column_and_concurrency_failure(bool async)
        => base.Rows_affected_result_column_and_concurrency_failure(async);

    [ConditionalTheory(Skip = PostgreSqlNoResultColumns)]
    [MemberData(nameof(IsAsyncData))]
    public override Task Update_with_output_parameter_and_rows_affected_result_column(bool async)
        => base.Update_with_output_parameter_and_rows_affected_result_column(async);

    [ConditionalTheory(Skip = PostgreSqlNoResultColumns)]
    [MemberData(nameof(IsAsyncData))]
    public override Task Update_with_output_parameter_and_rows_affected_result_column_concurrency_failure(bool async)
        => base.Update_with_output_parameter_and_rows_affected_result_column_concurrency_failure(async);

    [ConditionalTheory(Skip = PostgreSqlNoResultColumns)]
    [MemberData(nameof(IsAsyncData))]
    public override Task Tph(bool async)
        => base.Tph(async);

    [ConditionalTheory(Skip = PostgreSqlNoReturnValue)]
    [MemberData(nameof(IsAsyncData))]
    public override Task Rows_affected_return_value(bool async)
        => base.Rows_affected_return_value(async);

    [ConditionalTheory(Skip = PostgreSqlNoReturnValue)]
    [MemberData(nameof(IsAsyncData))]
    public override Task Rows_affected_return_value_and_concurrency_failure(bool async)
        => base.Rows_affected_return_value_and_concurrency_failure(async);

    // EF's TPC key is generated by an identity column where there is one. PostgreSQL's identity sequence is per table, as MySQL's
    // AUTO_INCREMENT is, so the child's key can repeat across the hierarchy's tables, which EF warns about. Behaviour reference
    // (not copied): Npgsql's StoredProcedureUpdateNpgsqlTest (PostgreSQL License):
    // https://github.com/npgsql/efcore.pg
    public override async Task Tpc(bool async)
    {
        var contextFactory = await InitializeAsync<DbContext>(
            modelBuilder =>
            {
                modelBuilder.Entity<Parent>().UseTpcMappingStrategy();
                modelBuilder.Entity<Child1>()
                    .UseTpcMappingStrategy()
                    .InsertUsingStoredProcedure(
                        nameof(Child1) + "_Insert",
                        spb => spb
                            .HasParameter(w => w.Id, pb => pb.IsOutput())
                            .HasParameter(w => w.Name)
                            .HasParameter(w => w.Child1Property))
                    .Property(e => e.Id).UseIdentityColumn();
            },
            seed: ctx => CreateStoredProcedures(ctx, UpdateProcedureSql.Of<PostgreSqlHost>(nameof(Tpc))),
            onConfiguring: optionsBuilder => optionsBuilder.ConfigureWarnings(w => w.Ignore(RelationalEventId.TpcStoreGeneratedIdentityWarning)));

        await using var context = contextFactory.CreateContext();
        var entity1 = new Child1 { Name = "Child", Child1Property = 8 };
        context.Set<Child1>().Add(entity1);
        if (async)
        {
            await context.SaveChangesAsync();
        }
        else
        {
            context.SaveChanges();
        }

        context.ChangeTracker.Clear();
        var entity2 = context.Set<Child1>().Single(b => b.Id == entity1.Id);
        Assert.Equal("Child", entity2.Name);
        Assert.Equal(8, entity2.Child1Property);
    }
}
